// Generates a Roc module of expectations from oracle records, so `roc test`
// checks the Roc parser against what Mermaid understood. Authoring only.
//
//   node golden.mjs <records-dir> <Output.roc> [--lenient-unsupported]
//
// Records are `*.oracle.json` beside named cases, or the `<key>.json` files of
// an oracle corpus cache. The module name is the output file's base name.
// A case named `unsupported-*` must be accepted by Mermaid and reported as
// unsupported by the Roc parser. Every other accepted case must parse to
// exactly the diagram Mermaid hands to layout, and every rejected case must
// be rejected for a reason other than an unsupported feature.
// --lenient-unsupported: for fuzz corpora, an input the Roc parser reports as
// unsupported is skipped whatever Mermaid did with it.
import fs from 'node:fs/promises';
import path from 'node:path';
import { expectedOutcome } from './model.mjs';

const [recordsDir, output] = process.argv.slice(2).filter(a => !a.startsWith('--'));
const lenient = process.argv.includes('--lenient-unsupported');
const moduleName = path.basename(output, '.roc');

const str = value => {
	let out = '"';
	for (const ch of value) {
		const cp = ch.codePointAt(0);
		if (ch === '"') out += '\\"';
		else if (ch === '\\') out += '\\\\';
		else if (ch === '$') out += '\\$';
		else if (ch === '\n') out += '\\n';
		else if (ch === '\t') out += '\\t';
		else if (ch === '\r') out += '\\r';
		else if (cp < 0x20 || cp > 0x7e) out += `\\u(${cp.toString(16).toUpperCase()})`;
		else out += ch;
	}
	return out + '"';
};
const list = (items, indent) => (items.length === 0 ? '[]' : `[\n${items.map(i => `${indent}\t${i},`).join('\n')}\n${indent}]`);
const strings = (items, indent) => list(items.map(str), indent);

const diagramLiteral = d => {
	const nodes = d.nodes.map(
		n =>
			`{ id: ${str(n.id)}, label: ${str(n.label)}, shape: ${n.shape}, container: ${n.container}, ` +
			`classes: ${strings(n.classes, '\t\t\t\t')}, styles: ${strings(n.styles, '\t\t\t\t')} }`,
	);
	const edges = d.edges.map(
		e =>
			`{ id: ${str(e.id)}, from: ${e.from}, to: ${e.to}, label: ${str(e.label)}, line: ${e.line}, ` +
			`start: ${e.start}, end: ${e.end}, length: ${e.length}, ` +
			`classes: ${strings(e.classes, '\t\t\t\t')}, styles: ${strings(e.styles, '\t\t\t\t')} }`,
	);
	const groups = d.groups.map(
		g => `{ id: ${str(g.id)}, title: ${str(g.title)}, container: ${g.container}, direction: ${g.direction}, classes: ${strings(g.classes, '\t\t\t\t')} }`,
	);
	const classes = d.classes.map(c => `{ name: ${str(c.name)}, styles: ${strings(c.styles, '\t\t\t\t')} }`);
	return (
		`{\n\t\t\tdirection: ${d.direction},\n` +
		`\t\t\tnodes: ${list(nodes, '\t\t\t')},\n` +
		`\t\t\tedges: ${list(edges, '\t\t\t')},\n` +
		`\t\t\tgroups: ${list(groups, '\t\t\t')},\n` +
		`\t\t\tclasses: ${list(classes, '\t\t\t')},\n\t\t}`
	);
};

const files = (await fs.readdir(recordsDir)).filter(f => f.endsWith('.json')).sort();
const blocks = [];
for (const file of files) {
	const record = JSON.parse(await fs.readFile(path.join(recordsDir, file), 'utf8'));
	if (!record.utf8) continue;
	const name = record.corpus_file ?? file.replace(/(\.oracle)?\.json$/, '');
	const found = expectedOutcome(record, name);
	const outcome = found.outcome === 'Accepted' ? `Accepted(\n\t\t${diagramLiteral(found.diagram)},\n\t)` : found.outcome;
	blocks.push(`## ${name}\nexpect ${moduleName}.agrees(\n\t${str(record.source)},\n\t${outcome},\n)`);
}

const lenientArm = lenient
	? `\t\t\t# A feature this package does not interpret yet is a skip, not a disagreement.\n\t\t\t(Err(problems), _) if problems.any(${moduleName}.is_unsupported) => True\n`
	: '';
const header = `import Flowchart

## Generated by tools/mermaid-oracle/golden.mjs. Do not edit; re-record the
## oracle and regenerate instead.
##
## Each expectation states what Mermaid did with one source text, so a
## failure here is a disagreement with Mermaid.
${moduleName} :: {}.{
\tExpected : [Accepted(Flowchart.Diagram), Rejected, Unsupported]

\tagrees : Str, Expected -> Bool
\tagrees = |source, expected|
\t\tmatch (Flowchart.parse(source), expected) {
\t\t\t(Ok(found), Accepted(wanted)) => found == wanted
\t\t\t(Err(problems), Rejected) => !problems.any(${moduleName}.is_unsupported)
\t\t\t(Err(problems), Unsupported) => problems.any(${moduleName}.is_unsupported)
${lenientArm}\t\t\t_ => False
\t\t}

\tis_unsupported : Flowchart.Problem -> Bool
\tis_unsupported = |problem|
\t\tmatch problem {
\t\t\tUnsupported(_) => True
\t\t\t_ => False
\t\t}
}
`;
await fs.writeFile(output, `${header}\n${blocks.join('\n\n')}\n`);
console.log(`${blocks.length} case(s) -> ${output}`);
