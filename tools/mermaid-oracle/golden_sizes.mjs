// Generates a Roc module of expectations that FlowSize measures every label
// and node as Mermaid did, so `roc test` (and `blueprint run check`) enforce
// sizing agreement without a browser. Authoring only.
//
//   node golden_sizes.mjs <Output.roc> <records-dir>...
//
// Expected values come from the records: each node's shape box, and each
// label's rows and text box at unit scale (`text.rows`, `text.box`).
// Tolerances:
// - 0.01px everywhere, except
// - 1.01px for heights (and so for shapes whose size follows the label's
//   height) of labels containing glyphs that make Chrome's line box 1px
//   taller: `|` and letters with stacked or below-baseline marks. Widths keep
//   0.01px there too.
// Labels that differ from Mermaid by design (see the README) are skipped: text
// with entity placeholders or NUL (decoded or removed here), and text with a
// `>` but no `<` (kept here, dropped by Mermaid).
import fs from 'node:fs/promises';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { expectedOutcome } from './model.mjs';

const [output, ...dirs] = process.argv.slice(2);
const moduleName = path.basename(output, '.roc');

const str = value => {
	let out = '"';
	for (const ch of value) {
		const cp = ch.codePointAt(0);
		if (ch === '"') out += '\\"';
		else if (ch === '\\') out += '\\\\';
		else if (ch === '$') out += '\\$';
		else if (ch === '\n') out += '\\n';
		else if (cp < 0x20 || cp > 0x7e) out += `\\u(${cp.toString(16).toUpperCase()})`;
		else out += ch;
	}
	return out + '"';
};
const num = n => (Number.isInteger(n) ? `${n}.0` : `${n}`);

// Characters whose glyphs make Chrome's line box 1px taller than the font's
// rounded ascent and descent.
const tall = text => /[|Ā-ɏ̀-ͯ]/.test(text);
const byDesign = text => /ﬂ°|\u0000/.test(text) || (text.includes('>') && !text.includes('<'));

const label = (text, theirs) => {
	if (!theirs || byDesign(text)) return 'Skip';
	return `Text({ lines: [${theirs.rows.map(str).join(', ')}], width: ${num(theirs.box.width)}, height: ${num(theirs.box.height)}, height_tolerance: ${tall(text) ? '1.01' : '0.01'} })`;
};

const blocks = [];
for (const dir of dirs) {
	for (const file of (await fs.readdir(dir)).filter(f => f.endsWith('.oracle.json')).sort()) {
		const record = JSON.parse(await fs.readFile(path.join(dir, file), 'utf8'));
		const name = file.replace(/\.oracle\.json$/, '');
		if (!record.accepted || !record.layout || !record.utf8) continue;
		// Entities and NUL: Mermaid's SVG labels draw them as written, these
		// labels decode or remove them (see the README).
		const fc = record.flowchart ?? { nodes: [], edges: [], subgraphs: [] };
		const rawLabels = [...fc.nodes.map(n => n.text ?? ''), ...fc.edges.map(e => e.text ?? ''), ...fc.subgraphs.map(s => s.title ?? '')];
		if (rawLabels.some(text => /ﬂ°|&|\u0000/.test(text))) {
			blocks.push(`## ${path.basename(dir)}/${name}: skipped, its labels differ from Mermaid's by design`);
			continue;
		}
		const wanted = expectedOutcome(record, name);
		if (wanted.outcome !== 'Accepted') continue;
		const d = wanted.diagram;
		const nodeBoxes = new Map(record.layout.nodes.map(n => [n.id, n]));
		const clusters = new Map(record.layout.clusters.map(c => [c.id, c]));
		const nodes = d.nodes.map(n => {
			const theirs = nodeBoxes.get(n.id);
			if (!theirs || theirs.missing || byDesign(n.label)) return 'Skip';
			const tolerance = tall(n.label) ? '1.01' : '0.01';
			return `Node({ width: ${num(theirs.box.width)}, height: ${num(theirs.box.height)}, tolerance: ${tolerance}, label: ${label(n.label, theirs.text)} })`;
		});
		const edges = d.edges.map((e, i) => {
			const theirs = record.layout.edges[i];
			if (!theirs || theirs.missing) return 'Skip';
			if (e.label === '') return 'NoLabel';
			return theirs.text && theirs.text.box.width > 0 ? label(e.label, theirs.text) : 'Skip';
		});
		const groups = d.groups.map(g => {
			const theirs = clusters.get(g.id);
			return theirs && !theirs.missing && theirs.text && theirs.text.box.width > 0 ? label(g.title, theirs.text) : 'Skip';
		});
		const list = items => (items.length === 0 ? '[]' : `[\n\t\t\t${items.join(',\n\t\t\t')},\n\t\t]`);
		blocks.push(
			`## ${path.basename(dir)}/${name}\nexpect ${moduleName}.agrees(\n\t${str(record.source)},\n\t{\n\t\tnodes: ${list(nodes)},\n\t\tedge_labels: ${list(edges)},\n\t\tgroup_titles: ${list(groups)},\n\t},\n)`,
		);
	}
}

const header = `import Flowchart
import FlowGeometry
import FlowSize

## Generated by tools/mermaid-oracle/golden_sizes.mjs. Do not edit; re-record the
## oracle and regenerate instead.
##
## Each expectation states the sizes Mermaid measured for one recorded case:
## node shape boxes, and each label's line breaks and text box. A failure here
## is a disagreement with Mermaid's measurements.
${moduleName} :: {}.{
\tExpectedText : [Text({ lines : List(Str), width : F64, height : F64, height_tolerance : F64 }), Skip]

\tExpected : {
\t\tnodes : List([Node({ width : F64, height : F64, tolerance : F64, label : ExpectedText }), Skip]),
\t\tedge_labels : List([NoLabel, Skip, Text({ lines : List(Str), width : F64, height : F64, height_tolerance : F64 })]),
\t\tgroup_titles : List(ExpectedText),
\t}

\tagrees : Str, Expected -> Bool
\tagrees = |source, expected|
\t\tmatch Flowchart.parse(source) {
\t\t\tErr(_) => False
\t\t\tOk(diagram) => {
\t\t\t\tsizes = FlowSize.sizes(diagram, FlowSize.mermaid)
\t\t\t\tnodes_agree = sizes.nodes.len() == expected.nodes.len()
\t\t\t\t\tand List.map2(sizes.nodes, expected.nodes, |found, wanted| ${moduleName}.node_agrees(found, wanted)).all(|ok| ok)
\t\t\t\tedges_agree = sizes.edge_labels.len() == expected.edge_labels.len()
\t\t\t\t\tand List.map2(sizes.edge_labels, expected.edge_labels, |found, wanted| ${moduleName}.edge_agrees(found, wanted)).all(|ok| ok)
\t\t\t\tgroups_agree = sizes.group_titles.len() == expected.group_titles.len()
\t\t\t\t\tand List.map2(sizes.group_titles, expected.group_titles, |found, wanted| ${moduleName}.text_agrees(found, wanted)).all(|ok| ok)
\t\t\t\tnodes_agree and edges_agree and groups_agree
\t\t\t}
\t\t}

\tclose : F64, F64, F64 -> Bool
\tclose = |a, b, tolerance| F64.abs(a - b) <= tolerance

\tnode_agrees : { width : F64, height : F64, label : FlowGeometry.TextBlock }, [Node({ width : F64, height : F64, tolerance : F64, label : ExpectedText }), Skip] -> Bool
\tnode_agrees = |found, wanted|
\t\tmatch wanted {
\t\t\tSkip => True
\t\t\tNode(n) =>
\t\t\t\t${moduleName}.close(found.width, n.width, n.tolerance)
\t\t\t\tand ${moduleName}.close(found.height, n.height, n.tolerance)
\t\t\t\tand ${moduleName}.text_agrees(found.label, n.label)
\t\t}

\ttext_agrees : FlowGeometry.TextBlock, ExpectedText -> Bool
\ttext_agrees = |found, wanted|
\t\tmatch wanted {
\t\t\tSkip => True
\t\t\tText(t) => found.lines == t.lines and ${moduleName}.close(found.width, t.width, 0.01) and ${moduleName}.close(found.height, t.height, t.height_tolerance)
\t\t}

\tedge_agrees : [None, Some(FlowGeometry.TextBlock)], [NoLabel, Skip, Text({ lines : List(Str), width : F64, height : F64, height_tolerance : F64 })] -> Bool
\tedge_agrees = |found, wanted|
\t\tmatch (found, wanted) {
\t\t\t(_, Skip) => True
\t\t\t(None, NoLabel) => True
\t\t\t(Some(block), Text(t)) => ${moduleName}.text_agrees(block, Text(t))
\t\t\t_ => False
\t\t}
}
`;
await fs.writeFile(output, `${header}\n${blocks.join('\n\n')}\n`);
try {
	execFileSync(process.env.ROC ?? 'roc', ['fmt', output], { stdio: 'ignore' });
} catch {
	console.warn(`could not run roc fmt on ${output}`);
}
console.log(`${blocks.length} case(s) -> ${output}`);
