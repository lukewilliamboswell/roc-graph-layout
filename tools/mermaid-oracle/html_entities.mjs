// Generates package-mermaid/HtmlEntities.roc from the WHATWG named character
// reference table (https://html.spec.whatwg.org/entities.json). Authoring only.
//
//   node html_entities.mjs entities.json ../../package-mermaid/HtmlEntities.roc
import fs from 'node:fs';

const [input, output] = process.argv.slice(2);
const table = JSON.parse(fs.readFileSync(input, 'utf8'));
const bytes = s => [...Buffer.from(s, 'utf8')];
const compare = (a, b) => {
	const x = bytes(a);
	const y = bytes(b);
	for (let i = 0; i < Math.min(x.length, y.length); i++) if (x[i] !== y[i]) return x[i] - y[i];
	return x.length - y.length;
};
const entries = Object.entries(table)
	.map(([name, { codepoints }]) => ({ name: name.slice(1), codepoints }))
	.sort((a, b) => compare(a.name, b.name));
const rows = entries.map(e => `\t\t{ name: "${e.name}", codepoints: [${e.codepoints.map(c => `0x${c.toString(16).toUpperCase()}`).join(', ')}] },`);
fs.writeFileSync(
	output,
	`## The HTML named character references, from the WHATWG table, sorted by the
## bytes of their names. A name ending in \`;\` must be written with it; the
## legacy names without one may also be written bare. Generated by
## tools/mermaid-oracle/html_entities.mjs; do not edit.
HtmlEntities :: {}.{
\tlongest_name : U64
\tlongest_name = ${Math.max(...entries.map(e => bytes(e.name).length))}

\tentries : List({ name : Str, codepoints : List(U32) })
\tentries = [
${rows.join('\n')}
\t]
}
`,
);
console.log(`${entries.length} entries -> ${output}`);
