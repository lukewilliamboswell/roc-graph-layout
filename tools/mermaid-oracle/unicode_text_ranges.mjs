// Prints the code point ranges of the flowchart lexer's UNICODE_TEXT rule as a
// Roc list, from Mermaid's flow.jison. Authoring only.
//
//   node unicode_text_ranges.mjs path/to/flow.jison
import fs from 'node:fs';

const source = fs.readFileSync(process.argv[2], 'utf8');
const start = source.indexOf('[\\u00AA');
const end = source.indexOf("return 'UNICODE_TEXT'");
const ranges = [];
for (const cls of source.slice(start, end).matchAll(/\[([^\]]*)\]/g)) {
	const items = cls[1].matchAll(/\\u([0-9A-Fa-f]{4})(?:-\\u([0-9A-Fa-f]{4}))?/g);
	for (const [, lo, hi] of items) ranges.push([parseInt(lo, 16), parseInt(hi ?? lo, 16)]);
}
ranges.sort((a, b) => a[0] - b[0]);
const hex = n => '0x' + n.toString(16).toUpperCase().padStart(4, '0');
const rows = [];
for (let i = 0; i < ranges.length; i += 6) {
	rows.push('\t\t' + ranges.slice(i, i + 6).map(([lo, hi]) => `(${hex(lo)}, ${hex(hi)})`).join(', ') + ',');
}
console.log(`# ${ranges.length} ranges generated by tools/mermaid-oracle/unicode_text_ranges.mjs`);
console.log(rows.join('\n'));
